-- категории техники
-- last_serial_number нужен для атомарной выдачи серийных номеров
-- serial_prefix: varchar(3), а не char(3) (так он без проблем маппится на string)
-- в hibernate; ровно три заглавные буквы гарантирует CHECK ниже
CREATE TABLE equipment_category (
                                    serial_prefix      varchar(3)  NOT NULL,
                                    name               varchar(30) NOT NULL,
                                    last_serial_number integer     NOT NULL DEFAULT 0,
                                    CONSTRAINT pk_equipment_category PRIMARY KEY (serial_prefix),
                                    CONSTRAINT uq_equipment_category_name UNIQUE (name),
                                    CONSTRAINT ck_equipment_category_prefix CHECK (serial_prefix ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_equipment_category_counter CHECK (last_serial_number >= 0)
);

-- модели техники: общие для всех экземпляров данные (бренд, название, тариф)
CREATE TABLE equipment_model (
                                 id              bigint GENERATED BY DEFAULT AS IDENTITY,
                                 category_prefix varchar(3)    NOT NULL,
                                 brand           varchar(50)   NOT NULL,
                                 name            varchar(100)  NOT NULL,
                                 description     text,
                                 daily_rate      numeric(10,2) NOT NULL,
                                 CONSTRAINT pk_equipment_model PRIMARY KEY (id),
                                 CONSTRAINT fk_equipment_model_category FOREIGN KEY (category_prefix)
                                     REFERENCES equipment_category (serial_prefix) ON DELETE RESTRICT,
                                 CONSTRAINT ck_equipment_model_rate CHECK (daily_rate >= 0)
);

-- UNIQUE (brand, name) без учёта регистра
CREATE UNIQUE INDEX uq_equipment_model_brand_name
    ON equipment_model (lower(brand), lower(name));

-- пользователи
-- уникальность логина и почты без учёта регистра (как findByUsername из ЛР1)
CREATE TABLE users (
                       id            bigint GENERATED BY DEFAULT AS IDENTITY,
                       username      varchar(30)  NOT NULL,
                       password_hash varchar(255) NOT NULL,
                       email         varchar(255) NOT NULL,
                       role          varchar(20)  NOT NULL,
                       CONSTRAINT pk_users PRIMARY KEY (id),
                       CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'MANAGER', 'CUSTOMER'))
);

CREATE UNIQUE INDEX uq_users_username ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email ON users (lower(email));

-- экземпляры техники.
CREATE TABLE equipment (
                           id            bigint GENERATED BY DEFAULT AS IDENTITY,
                           model_id      bigint      NOT NULL,
                           serial_number varchar(15) NOT NULL,
                           status        varchar(20) NOT NULL DEFAULT 'AVAILABLE',
                           condition     varchar(20) NOT NULL,
                           CONSTRAINT pk_equipment PRIMARY KEY (id),
                           CONSTRAINT uq_equipment_serial_number UNIQUE (serial_number),
                           CONSTRAINT fk_equipment_model FOREIGN KEY (model_id)
                               REFERENCES equipment_model (id) ON DELETE RESTRICT,
                           CONSTRAINT ck_equipment_serial_format CHECK (serial_number ~ '^[A-Z]{3}-[0-9]{5,}$'),
    CONSTRAINT ck_equipment_status
        CHECK (status IN ('AVAILABLE', 'RENTED', 'MAINTENANCE', 'RETIRED')),
    CONSTRAINT ck_equipment_condition
        CHECK (condition IN ('NEW', 'GOOD', 'WORN', 'NEEDS_REPAIR', 'DECOMMISSIONED')),
    -- списанная техника всегда в статусе RETIRED и наоборот
    CONSTRAINT ck_equipment_retired CHECK ((condition = 'DECOMMISSIONED') = (status = 'RETIRED'))
);

-- аренда
CREATE TABLE rental (
                        id           bigint GENERATED BY DEFAULT AS IDENTITY,
                        equipment_id bigint      NOT NULL,
                        customer_id  bigint      NOT NULL,
                        start_date   date        NOT NULL,
                        end_date     date        NOT NULL,
                        status       varchar(20) NOT NULL,
                        CONSTRAINT pk_rental PRIMARY KEY (id),
                        CONSTRAINT fk_rental_equipment FOREIGN KEY (equipment_id)
                            REFERENCES equipment (id) ON DELETE RESTRICT,
                        CONSTRAINT fk_rental_customer FOREIGN KEY (customer_id)
                            REFERENCES users (id) ON DELETE RESTRICT,
                        CONSTRAINT ck_rental_dates CHECK (end_date >= start_date),
                        CONSTRAINT ck_rental_status CHECK (status IN ('BOOKED', 'ACTIVE', 'RETURNED', 'OVERDUE')),
    -- одна и та же техника не может быть занята двумя незавершёнными арендами
    -- на пересекающиеся даты (границы включительно, как в Rental.overlapsWith)
    -- статусы здесь должны совпадать с проверкой в RentalService: BOOKED, ACTIVE, OVERDUE
                        CONSTRAINT ex_rental_no_overlap EXCLUDE USING gist (
        equipment_id WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (status IN ('BOOKED', 'ACTIVE', 'OVERDUE'))
);

-- заметки о состоянии техники (журнал изменений)
CREATE TABLE equipment_note (
                                id           bigint GENERATED BY DEFAULT AS IDENTITY,
                                equipment_id bigint    NOT NULL,
                                author_id    bigint    NOT NULL,
                                created_at   timestamp NOT NULL DEFAULT now(),
                                note_text    text      NOT NULL,
                                CONSTRAINT pk_equipment_note PRIMARY KEY (id),
                                CONSTRAINT fk_note_equipment FOREIGN KEY (equipment_id)
                                    REFERENCES equipment (id) ON DELETE RESTRICT,
                                CONSTRAINT fk_note_author FOREIGN KEY (author_id)
                                    REFERENCES users (id) ON DELETE RESTRICT,
                                CONSTRAINT ck_note_text CHECK (length(btrim(note_text)) > 0)
);

-- индексы (так как PostgreSQL не создаёт их на внешние ключи автоматически)
CREATE INDEX ix_equipment_model_category ON equipment_model (category_prefix);
CREATE INDEX ix_equipment_by_model ON equipment (model_id);
CREATE INDEX ix_rental_equipment ON rental (equipment_id);
CREATE INDEX ix_rental_customer ON rental (customer_id);
CREATE INDEX ix_note_equipment_created ON equipment_note (equipment_id, created_at);
CREATE INDEX ix_note_author ON equipment_note (author_id);

